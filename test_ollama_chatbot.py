class TestEnvironmentAndConfiguration(unittest.TestCase):
    """Verifies Requirement 4 & 5: .env.example, .gitignore, and dynamic environment loading."""

    def test_env_example_present_and_documented(self):
        self.assertTrue(os.path.exists(".env.example"), ".env.example file must exist in project root")
        with open(".env.example", "r", encoding="utf-8") as f:
            content = f.read()
        self.assertIn("OLLAMA_BASE_URL=http://localhost:11434", content)
        self.assertIn("OLLAMA_MODEL=your_model_name", content)
        self.assertIn("OLLAMA_API_KEY=your_api_key", content)

    def test_env_in_gitignore(self):
        self.assertTrue(os.path.exists(".gitignore"), ".gitignore file must exist")
        with open(".gitignore", "r", encoding="utf-8") as f:
            lines = [line.strip() for line in f.readlines()]
        self.assertIn(".env", lines, ".env must be explicitly ignored in .gitignore")

    def test_modular_ollama_configuration(self):
        """Verify changing OLLAMA_MODEL or OLLAMA_BASE_URL changes values dynamically."""
        client_test = OllamaClient()

        with patch.dict(os.environ, {
            "OLLAMA_BASE_URL": "http://192.168.1.100:11434",
            "OLLAMA_MODEL": "qwen2.5-coder:7b",
            "OLLAMA_API_KEY": "test-key-12345"
        }):
            self.assertEqual(client_test.base_url, "http://192.168.1.100:11434")
            self.assertEqual(client_test.model, "qwen2.5-coder:7b")
            self.assertEqual(client_test.api_key, "test-key-12345")

        # Switch model in environment
        with patch.dict(os.environ, {
            "OLLAMA_BASE_URL": "http://localhost:11434",
            "OLLAMA_MODEL": "mistral:latest",
            "OLLAMA_API_KEY": ""
        }):
            self.assertEqual(client_test.base_url, "http://localhost:11434")
            self.assertEqual(client_test.model, "mistral:latest")
            self.assertIsNone(client_test.api_key)


class TestOllamaChatbotFlow(unittest.TestCase):
    """Verifies Requirements 1, 2, 3, 7, 8, and 10: Pure LLM conversational generation."""

    @patch.object(OllamaClient, "chat_completion")
    def test_greeting_is_generated_by_ollama(self, mock_chat):
        mock_chat.return_value = {
            "content": "Welcome to ShopAI! I'm here to help you discover laptops, smartphones, fragrances, and more. What are you looking for today?",
            "model": "llama3.2",
            "error": None
        }

        resp = client.post("/api/chat", json={"message": "Hello!"})
        self.assertEqual(resp.status_code, 200)
        data = resp.json()

        # Verify LLM was called
        mock_chat.assert_called_once()
        self.assertEqual(data["reply"], "Welcome to ShopAI! I'm here to help you discover laptops, smartphones, fragrances, and more. What are you looking for today?")
        self.assertEqual(data["model_used"], "llama3.2")

    @patch.object(OllamaClient, "chat_completion")
    def test_missing_info_question_generated_by_ollama(self, mock_chat):
        mock_chat.return_value = {
            "content": "We have several great laptops available! Do you have a preferred screen size, processor requirement, or a specific budget in mind?",
            "model": "llama3.2",
            "error": None
        }

        resp = client.post("/api/chat", json={"message": "I need a laptop"})
        self.assertEqual(resp.status_code, 200)
        data = resp.json()

        self.assertIn("laptop", data["reply"].lower())
        self.assertIn("budget", data["reply"].lower())
        self.assertEqual(data["model_used"], "llama3.2")

    @patch.object(OllamaClient, "chat_completion")
    def test_progressive_conversation_flow(self, mock_chat):
        """
        Verifies the step-by-step product selection conversation:
        1. User provides general product type -> LLM asks concise question for missing spec -> 0 products shown.
        2. User answers -> LLM asks next single missing spec -> 0 products shown.
        3. User provides sufficient details -> LLM identifies ONE final product and asks to proceed/change -> exactly 1 product card.
        """
        # Turn 1: General product name -> LLM asks for budget
        mock_chat.return_value = {
            "content": "What is your budget for the laptop?",
            "model": "llama3.2",
            "error": None
        }
        resp1 = client.post("/api/chat", json={"message": "I want a laptop."})
        self.assertEqual(resp1.status_code, 200)
        d1 = resp1.json()
        self.assertEqual(d1["reply"], "What is your budget for the laptop?")
        self.assertEqual(len(d1["products"]), 0, "Must NOT show products while requirements are incomplete")

        # Turn 2: User answers budget -> LLM asks next single missing spec (brand)
        mock_chat.return_value = {
            "content": "Do you have a preferred brand?",
            "model": "llama3.2",
            "error": None
        }
        resp2 = client.post("/api/chat", json={
            "message": "Around $1500.",
            "history": [
                {"role": "user", "content": "I want a laptop."},
                {"role": "assistant", "content": "What is your budget for the laptop?"}
            ]
        })
        self.assertEqual(resp2.status_code, 200)
        d2 = resp2.json()
        self.assertEqual(d2["reply"], "Do you have a preferred brand?")
        self.assertEqual(len(d2["products"]), 0, "Must NOT show products while brand is still missing")

        # Turn 3: User answers brand -> LLM recommends exactly ONE final product and asks to proceed or change
        mock_chat.return_value = {
            "content": (
                "I recommend the New DELL XPS 13 9300 Laptop. It features an Intel Core i7 processor, 16GB RAM, "
                "512GB SSD, and is priced at $1,499.00 USD (~Rs. 415,500 PKR).\n\n"
                "Would you like to proceed with this item, or would you like to make any changes to your requirements? [PRODUCT_ID: 82]"
            ),
            "model": "llama3.2",
            "error": None
        }
        resp3 = client.post("/api/chat", json={
            "message": "Dell.",
            "history": [
                {"role": "user", "content": "I want a laptop."},
                {"role": "assistant", "content": "What is your budget for the laptop?"},
                {"role": "user", "content": "Around $1500."},
                {"role": "assistant", "content": "Do you have a preferred brand?"}
            ]
        })
        self.assertEqual(resp3.status_code, 200)
        d3 = resp3.json()
        self.assertIn("DELL XPS", d3["reply"])
        self.assertIn("proceed", d3["reply"].lower())
        self.assertNotIn("[PRODUCT_ID:", d3["reply"], "Internal product tag must be cleaned from user reply")
        self.assertEqual(len(d3["products"]), 1, "Must return EXACTLY ONE final product card")
        self.assertEqual(d3["products"][0]["id"], 82)
        self.assertIn("DELL XPS", d3["products"][0]["title"])

    @patch.object(OllamaClient, "chat_completion")
    def test_system_prompt_contains_product_selection_instructions(self, mock_chat):
        """Verifies system instructions mandate short responses, one question at a time, and 1 final product."""
        mock_chat.return_value = {
            "content": "What is your budget?",
            "model": "llama3.2",
            "error": None
        }
        client.post("/api/chat", json={"message": "I need a smartphone"})
        call_messages = mock_chat.call_args[1]["messages"]
        system_content = call_messages[0]["content"]

        self.assertIn("product-selection assistant", system_content.lower())
        self.assertIn("short, direct, and to the point", system_content.lower())
        self.assertIn("not immediately return a product", system_content.lower())
        self.assertIn("exactly one final matching product", system_content.lower())
        self.assertIn("whether they want to proceed or need any change", system_content.lower())

    @patch.object(OllamaClient, "chat_completion")
    def test_unavailable_category_dynamic_explanation(self, mock_chat):
        mock_chat.return_value = {
            "content": "We currently do not sell automobiles or cars in our store. Our catalog focuses on consumer electronics, fashion, beauty, and groceries. May I help you find a tech accessory or another product instead?",
            "model": "llama3.2",
            "error": None
        }

        resp = client.post("/api/chat", json={"message": "I need a sports car"})
        self.assertEqual(resp.status_code, 200)
        data = resp.json()
        self.assertIn("cars", data["reply"].lower())

    def test_technical_error_handling(self):
        """Verify technical failure handling when Ollama is unreachable (does not use hardcoded conversational text)."""
        with patch.object(OllamaClient, "chat_completion") as mock_chat:
            mock_chat.return_value = {
                "content": None,
                "model": "llama3.2",
                "error": "Failed to connect to Ollama at http://localhost:11434: Connection refused"
            }

            resp = client.post("/api/chat", json={"message": "Hello"})
            self.assertEqual(resp.status_code, 200)
            data = resp.json()
            self.assertIn("Technical Notice", data["reply"])
            self.assertEqual(len(data["products"]), 0)


